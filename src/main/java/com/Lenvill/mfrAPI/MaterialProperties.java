package com.Lenvill.mfrAPI;

public class MaterialProperties {
    int tier;
    float durability;
    float flexibility;
    float sharpness;
    float hardness;
    float resistance;
    float density;
    int melting_point;
    int rarity;
    int enchantability;
    int craft_tier;
    float craft_time_modifier;
    boolean unbreakable;

    //Getters
    public int getTier() {
        return tier;
    }

    public float getDurability() {
        return durability;
    }

    public float getFlexibility() {
        return flexibility;
    }

    public float getSharpness() {
        return sharpness;
    }

    public float getHardness() {
        return hardness;
    }

    public float getResistance() {
        return resistance;
    }

    public float getDensity() {
        return density;
    }

    public int getMelting_point() {
        return melting_point;
    }

    public int getRarity() {
        return rarity;
    }

    public int getEnchantability() {
        return enchantability;
    }

    public int getCraft_tier() {
        return craft_tier;
    }

    public float getCraft_time_modifier() {
        return craft_time_modifier;
    }

    public boolean isUnbreakable() {
        return unbreakable;
    }

    //Setters
    public void setTier(int tier) {
        this.tier = tier;
    }

    public void setDurability(float durability) {
        this.durability = durability;
    }

    public void setFlexibility(float flexibility) {
        this.flexibility = flexibility;
    }

    public void setSharpness(float sharpness) {
        this.sharpness = sharpness;
    }

    public void setHardness(float hardness) {
        this.hardness = hardness;
    }

    public void setResistance(float resistance) {
        this.resistance = resistance;
    }

    public void setDensity(float density) {
        this.density = density;
    }

    public void setMelting_point(int melting_point) {
        this.melting_point = melting_point;
    }

    public void setRarity(int rarity) {
        this.rarity = rarity;
    }

    public void setEnchantability(int enchantability) {
        this.enchantability = enchantability;
    }

    public void setCraft_tier(int craft_tier) {
        this.craft_tier = craft_tier;
    }

    public void setCraft_time_modifier(float craft_time_modifier) {
        this.craft_time_modifier = craft_time_modifier;
    }

    public void setUnbreakable(boolean unbreakable) {
        this.unbreakable = unbreakable;
    }
}
